if [[ "${BASH_VERSINFO[0]}" -eq 4 && "${BASH_VERSINFO[1]}" -ge 4 || "${BASH_VERSINFO[0]}" -gt 4 ]]; then
    complete -F _cursor__session -o nosort -o bashdefault -o default cursor-session
else
    complete -F _cursor__session -o bashdefault -o default cursor-session
fi
