_cursor__session() {
    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="cursor__session"
                ;;
            cursor__session,completions)
                cmd="cursor__session__subcmd__completions"
                ;;
            cursor__session,export)
                cmd="cursor__session__subcmd__export"
                ;;
            cursor__session,handoff)
                cmd="cursor__session__subcmd__handoff"
                ;;
            cursor__session,healthcheck)
                cmd="cursor__session__subcmd__healthcheck"
                ;;
            cursor__session,help)
                cmd="cursor__session__subcmd__help"
                ;;
            cursor__session,list)
                cmd="cursor__session__subcmd__list"
                ;;
            cursor__session,man)
                cmd="cursor__session__subcmd__man"
                ;;
            cursor__session,search)
                cmd="cursor__session__subcmd__search"
                ;;
            cursor__session,serve-clipboard)
                cmd="cursor__session__subcmd__serve__subcmd__clipboard"
                ;;
            cursor__session,show)
                cmd="cursor__session__subcmd__show"
                ;;
            cursor__session__subcmd__help,completions)
                cmd="cursor__session__subcmd__help__subcmd__completions"
                ;;
            cursor__session__subcmd__help,export)
                cmd="cursor__session__subcmd__help__subcmd__export"
                ;;
            cursor__session__subcmd__help,handoff)
                cmd="cursor__session__subcmd__help__subcmd__handoff"
                ;;
            cursor__session__subcmd__help,healthcheck)
                cmd="cursor__session__subcmd__help__subcmd__healthcheck"
                ;;
            cursor__session__subcmd__help,help)
                cmd="cursor__session__subcmd__help__subcmd__help"
                ;;
            cursor__session__subcmd__help,list)
                cmd="cursor__session__subcmd__help__subcmd__list"
                ;;
            cursor__session__subcmd__help,man)
                cmd="cursor__session__subcmd__help__subcmd__man"
                ;;
            cursor__session__subcmd__help,search)
                cmd="cursor__session__subcmd__help__subcmd__search"
                ;;
            cursor__session__subcmd__help,serve-clipboard)
                cmd="cursor__session__subcmd__help__subcmd__serve__subcmd__clipboard"
                ;;
            cursor__session__subcmd__help,show)
                cmd="cursor__session__subcmd__help__subcmd__show"
                ;;
            *)
                ;;
        esac
    done

    case "${cmd}" in
        cursor__session)
            opts="-v -h -V --storage --verbose --color --help --version list show search export handoff serve-clipboard healthcheck completions man help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 1 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --storage)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --color)
                    COMPREPLY=($(compgen -W "auto always never" -- "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        cursor__session__subcmd__completions)
            opts="-v -h --storage --verbose --color --help bash zsh fish"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --storage)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --color)
                    COMPREPLY=($(compgen -W "auto always never" -- "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        cursor__session__subcmd__export)
            opts="-v -h --format --out --session-id --workspace --source --limit --since --storage --verbose --color --help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                --format)
                    COMPREPLY=($(compgen -W "md json jsonl yaml" -- "${cur}"))
                    return 0
                    ;;
                --out)
                    COMPREPLY=()
                    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
                        compopt -o plusdirs
                    fi
                    return 0
                    ;;
                --session-id)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --workspace)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --source)
                    COMPREPLY=($(compgen -W "agent ide" -- "${cur}"))
                    return 0
                    ;;
                --limit)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --since)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --storage)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                --color)
                    COMPREPLY=($(compgen -W "auto always never" -- "${cur}"))
                    return 0
                    ;;
